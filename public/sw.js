import { precacheAndRoute } from 'workbox-precaching';
import { registerRoute } from 'workbox-routing';
import { CacheFirst, NetworkFirst, StaleWhileRevalidate } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
import {getAppVersion} from '../src/common/util/version.js'
import {removeStorageSelectedMapStyle} from '../src/common/map/core/MapView.jsx'
import {removeStorageNotificationToken} from '../src/common/components/NativeInterface.js'
import {removeStorageIsTrackingDevice} from '../src/common/util/isTrackingDeviceUtil.js'
import {removeStorageDevicesRoutesState} from '../src/common/util/devicesRoutesStateUtil.js'
import {removeStorageHistoryFlagState} from '../src/common/util/useHistoryFlagState.js'
import {removeStorageFirstTime, removeStorageLastTime} from '../src/common/util/usePersistedCheckInOutTime.js'
import {
  removeStorageNotifications,
  removeStorageNotificationsFlag,
} from '../src/common/util/usePersistedNotificationsState.js'

// Cache version management
const CACHE_VERSION = getAppVersion() || 'v1';
const CACHE_NAMES = {
  images: `images-cache-${CACHE_VERSION}`,
  api: `api-cache-${CACHE_VERSION}`,
  static: `static-assets-${CACHE_VERSION}`,
  map: `map-cache-${CACHE_VERSION}`
};

// Function to clean up old caches
const cleanupOldCaches = async () => {
  const cacheKeys = await caches.keys();
  const currentCaches = Object.values(CACHE_NAMES);

  return Promise.all(
    cacheKeys.map(cacheKey => {
      if (!currentCaches.includes(cacheKey)) {
        console.log('Deleting old cache:', cacheKey);
        removeStorageDevicesRoutesState()
        removeStorageIsTrackingDevice()
        removeStorageSelectedMapStyle()
        removeStorageNotificationToken()
        removeStorageHistoryFlagState()
        removeStorageFirstTime()
        removeStorageLastTime()
        removeStorageNotifications()
        removeStorageNotificationsFlag()
        window.localStorage.clear()
        return caches.delete(cacheKey);
      }
    })
  );
};

// Ensure the service worker is properly initialized
self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    Promise.all([
      clients.claim(),
      cleanupOldCaches()
    ])
  );
});

// Handle errors during service worker initialization
self.addEventListener('error', (event) => {
  console.error('Service Worker error:', event.error);
});

// Handle push notifications
self.addEventListener('push', (event) => {
  if (!event.data) return;

  try {
    const data = event.data.json();
    const options = {
      body: data.body || 'اعلان جدید',
      icon: data.icon || '/public/logo.png',
      badge: data.badge || '/public/logo.png',
      data: data.data || {},
      dir: 'rtl',
      lang: 'fa-IR',
      actions: data.actions || [],
      tag: 'push-notification',
      renotify: true,
      vibrate: [100, 50, 100],
      requireInteraction: true
    };

    event.waitUntil(
      self.registration.showNotification(data.title || 'اعلان', options)
    );
  } catch (error) {
    console.error('Error handling push notification:', error);
  }
});

self.addEventListener('notificationclick', function(event) {
  var notification = event.notification;
  var action = event.action;

  console.log(notification);

  if (action !== 'confirm') {
    console.log('Confirm was chosen');
    notification.close();
  } else {
    console.log(action);
    event.waitUntil(
      clients.matchAll()
        .then(function(clis) {
          var client = clis.find(function(c) {
            return c.visibilityState === 'visible';
          });

          if (client !== undefined) {
            client.navigate(notification.data.url);
            client.focus();
          } else {
            clients.openWindow(notification.data.url);
          }
          notification.close();
        })
    );
  }
});

self.addEventListener('notificationclose', function(event) {
  console.log('Notification was closed', event);
});

// Precache all assets generated by vite
try {
  precacheAndRoute(self.__WB_MANIFEST);
} catch (error) {
  console.error('Error during precache:', error);
}

// Cache images with CacheFirst strategy
registerRoute(
  ({ request }) => request.destination === 'image',
  new CacheFirst({
    cacheName: CACHE_NAMES.images,
    plugins: [
      new ExpirationPlugin({
        maxEntries: 1000,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
    ],
  })
);

